"""Generate distro-tailored harden install/apply shell scripts."""

from __future__ import annotations

from pathlib import Path

from fw_audit.harden.distro import DistroFamily, HostDistro

# Cloudflare malware-blocking DNS + Quad9 backup (operator-confirmed stage).
PRIMARY_DNS = "1.1.1.2"
BACKUP_DNS = "9.9.9.9"

CRON_SCHEDULE = "15 3 * * *"  # daily 03:15 (shield-audit drift)
DROP_CRON_SCHEDULE = "30 3 * * *"  # daily 03:30 (Spamhaus DROP refresh)
DEFAULT_DRIFT_WORKDIR = Path("/var/lib/shield-map")
DEFAULT_DROP_WORKDIR = Path("/var/lib/shield-map/drop")

# Official Spamhaus DROP feeds (do not fetch more than once per hour; daily is enough).
DROP_V4_URL = "https://www.spamhaus.org/drop/drop.txt"
DROP_V6_URL = "https://www.spamhaus.org/drop/dropv6.txt"


def _pkg_install_block(distro: HostDistro) -> str:
    if distro.family == DistroFamily.ARCH:
        return """# Arch / Omarchy (pacman)
need_root pacman -Sy --needed --noconfirm nftables fail2ban curl python-pip python-virtualenv
systemctl enable --now nftables.service 2>/dev/null || true
"""
    if distro.family == DistroFamily.UBUNTU:
        return """# Ubuntu / Debian (apt)
export DEBIAN_FRONTEND=noninteractive
need_root apt-get update -y
need_root apt-get install -y nftables fail2ban curl python3-pip python3-venv
need_root systemctl enable --now nftables.service 2>/dev/null || true
"""
    if distro.family == DistroFamily.REDHAT:
        return """# Red Hat family (dnf/yum)
if command -v dnf >/dev/null 2>&1; then
  PKG=dnf
else
  PKG=yum
fi
need_root "$PKG" install -y nftables fail2ban curl python3-pip
need_root systemctl enable --now nftables.service 2>/dev/null || true
"""
    return """echo "Unsupported distro family; install nftables and fail2ban manually." >&2
exit 1
"""


def _drop_refresh_script_body(drop_workdir: Path) -> str:
    """Cron-friendly Spamhaus DROP downloader / nftables loader (safe on failure)."""
    return f"""#!/usr/bin/env bash
# Spamhaus DROP refresh — generated by shield-up
# Feeds: {DROP_V4_URL}  /  {DROP_V6_URL}
# Policy: at most once per hour; on download/parse failure keep previous sets.
set -euo pipefail

WORKDIR="{drop_workdir}"
STAMP="$WORKDIR/last-success"
MIN_INTERVAL_SEC=3600
LOCK="$WORKDIR/.refresh.lock"
NFT_FRAGMENT="$WORKDIR/shield-drop.nft"
LIST4="$WORKDIR/drop4.cidrs"
LIST6="$WORKDIR/dropv6.cidrs"
TMP="$WORKDIR/.tmp"
LOG_TAG="shield-drop"

log() {{ echo "[$LOG_TAG] $*" >&2; }}

need_root() {{
  if [[ "${{EUID:-$(id -u)}}" -ne 0 ]]; then
    exec sudo "$@"
  else
    "$@"
  fi
}}

fetch() {{
  local url="$1" out="$2"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL --connect-timeout 20 --max-time 120 -o "$out" "$url"
  elif command -v wget >/dev/null 2>&1; then
    wget -q -O "$out" "$url"
  else
    log "Neither curl nor wget found"
    return 127
  fi
}}

parse_drop() {{
  # Spamhaus DROP: "CIDR ; SBL…" — strip comments / blank lines
  local src="$1" dest="$2"
  awk '
    /^[[:space:]]*#/ {{ next }}
    /^[[:space:]]*;/ {{ next }}
    NF == 0 {{ next }}
    {{
      line=$0
      sub(/;.*/, "", line)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", line)
      if (line ~ /^[0-9a-fA-F:.]+\\/[0-9]+$/) print line
    }}
  ' "$src" > "$dest"
  [[ -s "$dest" ]]
}}

mkdir -p "$WORKDIR" "$TMP"
FETCHED=0

# Simple flock if available
if command -v flock >/dev/null 2>&1; then
  exec 9>"$LOCK"
  flock -n 9 || {{ log "Another refresh is running; exiting"; exit 0; }}
fi

do_fetch=1
if [[ -f "$STAMP" ]]; then
  now=$(date +%s)
  last=$(stat -c %Y "$STAMP" 2>/dev/null || stat -f %m "$STAMP" 2>/dev/null || echo 0)
  if (( now - last < MIN_INTERVAL_SEC )); then
    log "Skipping fetch (last success < ${{MIN_INTERVAL_SEC}}s ago); re-applying existing lists"
    do_fetch=0
  fi
fi

if [[ "$do_fetch" -eq 1 ]]; then
  if ! fetch "{DROP_V4_URL}" "$TMP/drop.txt"; then
    log "IPv4 DROP download failed; keeping previous set"
    [[ -s "$LIST4" || -s "$LIST6" ]] || exit 1
    do_fetch=0
  elif ! fetch "{DROP_V6_URL}" "$TMP/dropv6.txt"; then
    log "IPv6 DROP download failed; keeping previous set"
    [[ -s "$LIST4" || -s "$LIST6" ]] || exit 1
    do_fetch=0
  elif ! parse_drop "$TMP/drop.txt" "$TMP/drop4.cidrs"; then
    log "IPv4 DROP parse produced empty list; keeping previous set"
    [[ -s "$LIST4" || -s "$LIST6" ]] || exit 1
    do_fetch=0
  elif ! parse_drop "$TMP/dropv6.txt" "$TMP/dropv6.cidrs"; then
    log "IPv6 DROP parse produced empty list; keeping previous set"
    [[ -s "$LIST4" || -s "$LIST6" ]] || exit 1
    do_fetch=0
  else
    mv -f "$TMP/drop4.cidrs" "$LIST4"
    mv -f "$TMP/dropv6.cidrs" "$LIST6"
    FETCHED=1
  fi
fi

# Build nftables fragment from on-disk lists (never wipe sets if lists missing)
if [[ ! -s "$LIST4" && ! -s "$LIST6" ]]; then
  log "No DROP CIDR lists on disk; refusing to clear nft sets"
  exit 1
fi

{{
  echo "table inet shield_drop {{"
  echo "  set shield_drop4 {{"
  echo "    type ipv4_addr"
  echo "    flags interval"
  if [[ -s "$LIST4" ]]; then
    echo -n "    elements = {{ "
    paste -sd, "$LIST4" | tr -d '\\n'
    echo " }}"
  fi
  echo "  }}"
  echo "  set shield_drop6 {{"
  echo "    type ipv6_addr"
  echo "    flags interval"
  if [[ -s "$LIST6" ]]; then
    echo -n "    elements = {{ "
    paste -sd, "$LIST6" | tr -d '\\n'
    echo " }}"
  fi
  echo "  }}"
  echo "  chain input {{"
  echo "    type filter hook input priority -10; policy accept;"
  echo "    ip saddr @shield_drop4 drop comment \\"spamhaus-drop\\""
  echo "    ip6 saddr @shield_drop6 drop comment \\"spamhaus-drop\\""
  echo "  }}"
  echo "  chain output {{"
  echo "    type filter hook output priority -10; policy accept;"
  echo "    ip daddr @shield_drop4 drop comment \\"spamhaus-drop\\""
  echo "    ip6 daddr @shield_drop6 drop comment \\"spamhaus-drop\\""
  echo "  }}"
  echo "}}"
}} > "$TMP/shield-drop.nft"

# Keep last-known-good fragment so a failed apply can be restored
if [[ -f "$NFT_FRAGMENT" ]]; then
  cp -f "$NFT_FRAGMENT" "$TMP/shield-drop.prev.nft"
fi

# Replace only the shield_drop table (do not flush other rulesets)
need_root nft delete table inet shield_drop 2>/dev/null || true
if ! need_root nft -f "$TMP/shield-drop.nft"; then
  log "nft apply failed; restoring previous shield_drop table if available"
  if [[ -f "$TMP/shield-drop.prev.nft" ]]; then
    need_root nft -f "$TMP/shield-drop.prev.nft" || true
  fi
  exit 1
fi
mv -f "$TMP/shield-drop.nft" "$NFT_FRAGMENT"
# Only advance the rate-limit stamp after a successful download+parse
if [[ "$FETCHED" -eq 1 ]]; then
  date -u +"%%Y-%%m-%%dT%%H:%%M:%%SZ" > "$STAMP" 2>/dev/null \\
    || date -u > "$STAMP"
fi
count4=0; count6=0
[[ -f "$LIST4" ]] && count4=$(wc -l < "$LIST4" | tr -d ' ')
[[ -f "$LIST6" ]] && count6=$(wc -l < "$LIST6" | tr -d ' ')
log "Loaded Spamhaus DROP: ${{count4}} IPv4 + ${{count6}} IPv6 CIDRs into inet shield_drop"
"""


def write_harden_scripts(
    scripts_dir: Path,
    distro: HostDistro,
    *,
    host_out: Path,
    baseline_xml: Path,
    fw_audit_bin: str = "shield-audit",
    drift_workdir: Path | None = None,
    drop_workdir: Path | None = None,
) -> dict[str, Path]:
    """Write shell scripts tailored to the detected distro family.

    Returns a map of logical name → path.
    """
    scripts_dir.mkdir(parents=True, exist_ok=True)
    drift_workdir = drift_workdir or DEFAULT_DRIFT_WORKDIR
    drop_workdir = drop_workdir or DEFAULT_DROP_WORKDIR
    host_out_s = str(host_out.resolve())
    baseline_s = str(baseline_xml.resolve())
    nft_rules = host_out / "rules-nftables.conf"
    jail = host_out / "jail.d" / "shield-map.conf"
    canary_conf = host_out / ".opencanary.conf"

    paths: dict[str, Path] = {}

    common_header = f"""#!/usr/bin/env bash
# Generated by shield-up for {distro.pretty_name}
# family={distro.family.value} id={distro.id} pkg={distro.package_manager}
# REVIEW BEFORE APPLY — home-lab use only
set -euo pipefail

need_root() {{
  if [[ "${{EUID:-$(id -u)}}" -ne 0 ]]; then
    exec sudo "$@"
  else
    "$@"
  fi
}}
"""

    install_deps = scripts_dir / "01-install-deps.sh"
    install_deps.write_text(
        common_header + "\n" + _pkg_install_block(distro) + 'echo "Dependencies ready."\n',
        encoding="utf-8",
    )
    paths["install_deps"] = install_deps

    apply_fw = scripts_dir / "02-apply-firewall.sh"
    apply_fw.write_text(
        common_header
        + f"""
RULES="{nft_rules}"
if [[ ! -f "$RULES" ]]; then
  echo "Missing nftables rules: $RULES" >&2
  exit 1
fi
need_root nft -f "$RULES"
echo "Applied nftables rules from $RULES"
# rules-nftables.conf starts with 'flush ruleset' — re-apply Spamhaus DROP if installed
if [[ -x /usr/local/sbin/shield-drop-refresh.sh ]]; then
  /usr/local/sbin/shield-drop-refresh.sh \\
    || echo "Warning: shield-drop-refresh failed after firewall apply" >&2
fi
""",
        encoding="utf-8",
    )
    paths["apply_firewall"] = apply_fw

    setup_f2b = scripts_dir / "03-setup-fail2ban.sh"
    setup_f2b.write_text(
        common_header
        + f"""
JAIL_SRC="{jail}"
if [[ ! -f "$JAIL_SRC" ]]; then
  echo "Missing Fail2ban jail drop-in: $JAIL_SRC" >&2
  exit 1
fi
need_root mkdir -p /etc/fail2ban/jail.d
need_root cp "$JAIL_SRC" /etc/fail2ban/jail.d/shield-map.conf
# Remove legacy drop-in name if present
need_root rm -f /etc/fail2ban/jail.d/fw-audit.conf
need_root systemctl enable --now fail2ban.service
need_root systemctl restart fail2ban.service
echo "Fail2ban jail installed from $JAIL_SRC"
""",
        encoding="utf-8",
    )
    paths["setup_fail2ban"] = setup_f2b

    setup_canary = scripts_dir / "04-setup-opencanary.sh"
    setup_canary.write_text(
        common_header
        + f"""
CONF_SRC="{canary_conf}"
VENV_DIR="/opt/shield-map-opencanary"
if [[ ! -f "$CONF_SRC" ]]; then
  echo "Missing OpenCanary conf: $CONF_SRC" >&2
  exit 1
fi
need_root mkdir -p "$VENV_DIR"
if [[ ! -x "$VENV_DIR/bin/opencanaryd" ]]; then
  need_root python3 -m venv "$VENV_DIR"
  need_root "$VENV_DIR/bin/pip" install --upgrade pip
  need_root "$VENV_DIR/bin/pip" install opencanary
fi
need_root mkdir -p /etc/opencanary
need_root cp "$CONF_SRC" /etc/opencanary/opencanary.conf
UNIT=/etc/systemd/system/opencanary.service
need_root tee "$UNIT" >/dev/null <<'UNIT'
[Unit]
Description=OpenCanary (shield-up defaults)
After=network.target

[Service]
Type=simple
ExecStart=/opt/shield-map-opencanary/bin/opencanaryd --dev --uid=nobody --gid=nogroup
WorkingDirectory=/etc/opencanary
Restart=on-failure

[Install]
WantedBy=multi-user.target
UNIT
if [[ ! -e /etc/opencanary.conf ]]; then
  need_root ln -s /etc/opencanary/opencanary.conf /etc/opencanary.conf || true
fi
need_root systemctl daemon-reload
need_root systemctl enable --now opencanary.service
echo "OpenCanary installed with defaults from $CONF_SRC"
""",
        encoding="utf-8",
    )
    paths["setup_opencanary"] = setup_canary

    setup_dns = scripts_dir / "05-setup-dns.sh"
    setup_dns.write_text(
        common_header
        + f"""
PRIMARY="{PRIMARY_DNS}"
BACKUP="{BACKUP_DNS}"
DROPIN_DIR=/etc/systemd/resolved.conf.d
DROPIN="$DROPIN_DIR/shield-map-filtered-dns.conf"

if systemctl is-active --quiet systemd-resolved 2>/dev/null \\
   || [[ -d /etc/systemd/resolved.conf.d ]] || [[ -f /etc/systemd/resolved.conf ]]; then
  need_root mkdir -p "$DROPIN_DIR"
  need_root tee "$DROPIN" >/dev/null <<EOF
[Resolve]
DNS=$PRIMARY $BACKUP
FallbackDNS=$BACKUP
DNSOverTLS=no
EOF
  need_root systemctl restart systemd-resolved.service 2>/dev/null || true
  echo "Configured systemd-resolved: $PRIMARY (primary), $BACKUP (backup)"
elif command -v nmcli >/dev/null 2>&1; then
  CONN=$(nmcli -t -f NAME,DEVICE connection show --active | head -n1 | cut -d: -f1)
  if [[ -n "$CONN" ]]; then
    need_root nmcli connection modify "$CONN" ipv4.dns "$PRIMARY $BACKUP"
    need_root nmcli connection modify "$CONN" ipv4.ignore-auto-dns yes
    need_root nmcli connection up "$CONN"
    echo "Configured NetworkManager connection '$CONN': $PRIMARY / $BACKUP"
  else
    echo "No active NetworkManager connection found." >&2
    exit 1
  fi
else
  need_root tee /etc/resolv.conf >/dev/null <<EOF
# Managed by shield-up — filtered DNS
nameserver $PRIMARY
nameserver $BACKUP
EOF
  echo "Wrote /etc/resolv.conf with $PRIMARY and $BACKUP"
fi
""",
        encoding="utf-8",
    )
    paths["setup_dns"] = setup_dns

    drop_refresh = scripts_dir / "shield-drop-refresh.sh"
    drop_refresh.write_text(_drop_refresh_script_body(drop_workdir), encoding="utf-8")
    paths["drop_refresh"] = drop_refresh

    setup_drop = scripts_dir / "07-setup-drop.sh"
    setup_drop.write_text(
        common_header
        + f"""
REFRESH_SRC="{drop_refresh}"
REFRESH_DST="/usr/local/sbin/shield-drop-refresh.sh"
CRON_FILE="/etc/cron.d/shield-drop"
need_root install -m 0755 "$REFRESH_SRC" "$REFRESH_DST"
need_root mkdir -p "{drop_workdir}"
# Initial load (fails closed: keeps empty/previous; refresh logs on error)
set +e
need_root "$REFRESH_DST"
rc=$?
set -e
if [[ $rc -ne 0 ]]; then
  echo "Warning: initial Spamhaus DROP load failed (rc=$rc); cron will retry" >&2
fi
need_root tee "$CRON_FILE" >/dev/null <<EOF
# Spamhaus DROP refresh (generated by shield-up) — daily; script also rate-limits to 1/hour
{DROP_CRON_SCHEDULE} root $REFRESH_DST >> /var/log/shield-drop.log 2>&1
EOF
need_root chmod 644 "$CRON_FILE"
echo "Installed Spamhaus DROP refresh ($REFRESH_DST) and cron $CRON_FILE ($DROP_CRON_SCHEDULE)"
echo "Lists/logs under {drop_workdir} and /var/log/shield-drop.log"
""",
        encoding="utf-8",
    )
    paths["setup_drop"] = setup_drop

    drift_sh = scripts_dir / "shield-audit-cron.sh"
    drift_sh.write_text(
        f"""#!/usr/bin/env bash
# Daily drift check installed by shield-up (invokes shield-audit)
set -euo pipefail
WORKDIR="{drift_workdir}"
BASELINE="{drift_workdir}/baseline-audit-report.xml"
BIN="{fw_audit_bin}"
mkdir -p "$WORKDIR/current"
if command -v "$BIN" >/dev/null 2>&1; then
  exec "$BIN" --baseline "$BASELINE" --output-dir "$WORKDIR/current"
fi
# Fallback: python module entry when console script not on PATH
if command -v python3 >/dev/null 2>&1; then
  exec python3 -c "from fw_audit.entrypoints import shield_audit; import sys; \\
sys.argv = ['shield-audit', '--baseline', '$BASELINE', '--output-dir', '$WORKDIR/current']; \\
shield_audit()"
fi
echo "shield-audit not found on PATH" >&2
exit 127
""",
        encoding="utf-8",
    )
    paths["drift"] = drift_sh

    setup_cron = scripts_dir / "06-setup-cron.sh"
    setup_cron.write_text(
        common_header
        + f"""
DRIFT_SRC="{drift_sh}"
DRIFT_DST="/usr/local/sbin/shield-audit-cron.sh"
CRON_FILE="/etc/cron.d/shield-audit"
need_root install -m 0755 "$DRIFT_SRC" "$DRIFT_DST"
need_root mkdir -p "{drift_workdir}"
need_root cp "{baseline_s}" "{drift_workdir}/baseline-audit-report.xml" 2>/dev/null || true
need_root tee "$CRON_FILE" >/dev/null <<EOF
# shield-audit configuration drift (generated by shield-up)
{CRON_SCHEDULE} root $DRIFT_DST >> /var/log/shield-audit.log 2>&1
EOF
need_root chmod 644 "$CRON_FILE"
# Clean up legacy fw-audit cron if present
need_root rm -f /etc/cron.d/fw-audit-drift /usr/local/sbin/fw-audit-drift.sh
echo "Installed cron job $CRON_FILE ($CRON_SCHEDULE)"
""",
        encoding="utf-8",
    )
    paths["setup_cron"] = setup_cron

    run_all = scripts_dir / "00-run-all.sh"
    run_all.write_text(
        common_header
        + f"""
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
"$SCRIPT_DIR/01-install-deps.sh"
"$SCRIPT_DIR/02-apply-firewall.sh"
"$SCRIPT_DIR/03-setup-fail2ban.sh"
# Optional stages — pass OPENCANARY=1 DNS=1 DROP=1 to enable
if [[ "${{OPENCANARY:-0}}" == "1" ]]; then
  "$SCRIPT_DIR/04-setup-opencanary.sh"
fi
if [[ "${{DNS:-0}}" == "1" ]]; then
  "$SCRIPT_DIR/05-setup-dns.sh"
fi
if [[ "${{DROP:-0}}" == "1" ]]; then
  "$SCRIPT_DIR/07-setup-drop.sh"
fi
"$SCRIPT_DIR/06-setup-cron.sh"
echo "shield-up scripts finished for {distro.pretty_name}."
""",
        encoding="utf-8",
    )
    paths["run_all"] = run_all

    readme = scripts_dir / "README.txt"
    readme.write_text(
        "\n".join(
            [
                "shield-up Linux harden scripts",
                "=" * 40,
                f"Host: {distro.pretty_name}",
                f"Family: {distro.family.value} (package manager: {distro.package_manager})",
                f"Omarchy: {distro.is_omarchy}",
                "",
                "Stage order:",
                "  1. discover   — ss/netstat open ports",
                "  2. configure  — nftables + Fail2ban + OpenCanary artifacts",
                "  3. firewall   — 02-apply-firewall.sh",
                "  4. fail2ban   — 01-install-deps.sh + 03-setup-fail2ban.sh",
                "  5. opencanary — 04-setup-opencanary.sh (optional Y/n)",
                "  6. dns        — 05-setup-dns.sh → "
                f"{PRIMARY_DNS} + {BACKUP_DNS} backup (optional Y/n)",
                "  7. drop       — 07-setup-drop.sh Spamhaus DROP → nftables "
                "(optional Y/n; daily refresh)",
                "  8. cron       — 06-setup-cron.sh (shield-audit drift)",
                "",
                "Spamhaus DROP notes:",
                f"  - Feeds: {DROP_V4_URL} / {DROP_V6_URL}",
                "  - Size: small (~1k IPv4 CIDRs); slow-changing; low false-positive",
                "  - Refresh: daily cron + in-script 1/hour rate limit",
                "  - Failure: keep previous nft sets; never wipe on download error",
                f"  - State: {drop_workdir} ; log: /var/log/shield-drop.log",
                "",
                f"Artifacts under: {host_out_s}",
                "Prefer: shield-up --apply  (prompts for optional stages)",
                "Or run scripts individually after review.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    paths["readme"] = readme

    for path in paths.values():
        if path.suffix == ".sh":
            path.chmod(path.stat().st_mode | 0o111)

    return paths
