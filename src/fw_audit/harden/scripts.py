"""Generate distro-tailored harden install/apply shell scripts."""

from __future__ import annotations

from pathlib import Path

from fw_audit.harden.distro import DistroFamily, HostDistro

# Cloudflare malware-blocking DNS + Quad9 backup (operator-confirmed stage).
PRIMARY_DNS = "1.1.1.2"
BACKUP_DNS = "9.9.9.9"

CRON_SCHEDULE = "15 3 * * *"  # daily 03:15


def _pkg_install_block(distro: HostDistro) -> str:
    if distro.family == DistroFamily.ARCH:
        return """# Arch / Omarchy (pacman)
need_root pacman -Sy --needed --noconfirm nftables fail2ban python-pip python-virtualenv
systemctl enable --now nftables.service 2>/dev/null || true
"""
    if distro.family == DistroFamily.UBUNTU:
        return """# Ubuntu / Debian (apt)
export DEBIAN_FRONTEND=noninteractive
need_root apt-get update -y
need_root apt-get install -y nftables fail2ban python3-pip python3-venv
need_root systemctl enable --now nftables.service 2>/dev/null || true
"""
    if distro.family == DistroFamily.REDHAT:
        return """# Red Hat family (dnf/yum)
if command -v dnf >/dev/null 2>&1; then
  PKG=dnf
else
  PKG=yum
fi
need_root "$PKG" install -y nftables fail2ban python3-pip
need_root systemctl enable --now nftables.service 2>/dev/null || true
"""
    return """echo "Unsupported distro family; install nftables and fail2ban manually." >&2
exit 1
"""


def write_harden_scripts(
    scripts_dir: Path,
    distro: HostDistro,
    *,
    host_out: Path,
    baseline_xml: Path,
    fw_audit_bin: str = "fw-audit",
    drift_workdir: Path | None = None,
) -> dict[str, Path]:
    """Write shell scripts tailored to the detected distro family.

    Returns a map of logical name → path.
    """
    scripts_dir.mkdir(parents=True, exist_ok=True)
    drift_workdir = drift_workdir or Path("/var/lib/fw-audit")
    host_out_s = str(host_out.resolve())
    baseline_s = str(baseline_xml.resolve())
    nft_rules = host_out / "rules-nftables.conf"
    jail = host_out / "jail.d" / "fw-audit.conf"
    canary_conf = host_out / ".opencanary.conf"

    paths: dict[str, Path] = {}

    common_header = f"""#!/usr/bin/env bash
# Generated by fw-audit harden for {distro.pretty_name}
# family={distro.family.value} id={distro.id} pkg={distro.package_manager}
# REVIEW BEFORE APPLY — home-lab use only
set -euo pipefail

need_root() {{
  if [[ "${{EUID:-$(id -u)}}" -ne 0 ]]; then
    exec sudo "$@"
  else
    "$@"
  fi
}}
"""

    install_deps = scripts_dir / "01-install-deps.sh"
    install_deps.write_text(
        common_header + "\n" + _pkg_install_block(distro) + 'echo "Dependencies ready."\n',
        encoding="utf-8",
    )
    paths["install_deps"] = install_deps

    apply_fw = scripts_dir / "02-apply-firewall.sh"
    apply_fw.write_text(
        common_header
        + f"""
RULES="{nft_rules}"
if [[ ! -f "$RULES" ]]; then
  echo "Missing nftables rules: $RULES" >&2
  exit 1
fi
need_root nft -f "$RULES"
echo "Applied nftables rules from $RULES"
""",
        encoding="utf-8",
    )
    paths["apply_firewall"] = apply_fw

    setup_f2b = scripts_dir / "03-setup-fail2ban.sh"
    setup_f2b.write_text(
        common_header
        + f"""
JAIL_SRC="{jail}"
if [[ ! -f "$JAIL_SRC" ]]; then
  echo "Missing Fail2ban jail drop-in: $JAIL_SRC" >&2
  exit 1
fi
need_root mkdir -p /etc/fail2ban/jail.d
need_root cp "$JAIL_SRC" /etc/fail2ban/jail.d/fw-audit.conf
need_root systemctl enable --now fail2ban.service
need_root systemctl restart fail2ban.service
echo "Fail2ban jail installed from $JAIL_SRC"
""",
        encoding="utf-8",
    )
    paths["setup_fail2ban"] = setup_f2b

    setup_canary = scripts_dir / "04-setup-opencanary.sh"
    setup_canary.write_text(
        common_header
        + f"""
CONF_SRC="{canary_conf}"
VENV_DIR="/opt/fw-audit-opencanary"
if [[ ! -f "$CONF_SRC" ]]; then
  echo "Missing OpenCanary conf: $CONF_SRC" >&2
  exit 1
fi
need_root mkdir -p "$VENV_DIR"
if [[ ! -x "$VENV_DIR/bin/opencanaryd" ]]; then
  need_root python3 -m venv "$VENV_DIR"
  need_root "$VENV_DIR/bin/pip" install --upgrade pip
  need_root "$VENV_DIR/bin/pip" install opencanary
fi
need_root mkdir -p /etc/opencanary
need_root cp "$CONF_SRC" /etc/opencanary/opencanary.conf
# Default unit: run opencanaryd from the venv with generated config
UNIT=/etc/systemd/system/opencanary.service
need_root tee "$UNIT" >/dev/null <<'UNIT'
[Unit]
Description=OpenCanary (fw-audit harden defaults)
After=network.target

[Service]
Type=simple
ExecStart=/opt/fw-audit-opencanary/bin/opencanaryd --dev --uid=nobody --gid=nogroup
WorkingDirectory=/etc/opencanary
Restart=on-failure

[Install]
WantedBy=multi-user.target
UNIT
# Prefer conf next to cwd; also symlink classic path if absent
if [[ ! -e /etc/opencanary.conf ]]; then
  need_root ln -s /etc/opencanary/opencanary.conf /etc/opencanary.conf || true
fi
need_root systemctl daemon-reload
need_root systemctl enable --now opencanary.service
echo "OpenCanary installed with defaults from $CONF_SRC"
""",
        encoding="utf-8",
    )
    paths["setup_opencanary"] = setup_canary

    setup_dns = scripts_dir / "05-setup-dns.sh"
    setup_dns.write_text(
        common_header
        + f"""
PRIMARY="{PRIMARY_DNS}"
BACKUP="{BACKUP_DNS}"
DROPIN_DIR=/etc/systemd/resolved.conf.d
DROPIN="$DROPIN_DIR/fw-audit-filtered-dns.conf"

if systemctl is-active --quiet systemd-resolved 2>/dev/null \\
   || [[ -d /etc/systemd/resolved.conf.d ]] || [[ -f /etc/systemd/resolved.conf ]]; then
  need_root mkdir -p "$DROPIN_DIR"
  need_root tee "$DROPIN" >/dev/null <<EOF
[Resolve]
DNS=$PRIMARY $BACKUP
FallbackDNS=$BACKUP
DNSOverTLS=no
EOF
  need_root systemctl restart systemd-resolved.service 2>/dev/null || true
  echo "Configured systemd-resolved: $PRIMARY (primary), $BACKUP (backup)"
elif command -v nmcli >/dev/null 2>&1; then
  CONN=$(nmcli -t -f NAME,DEVICE connection show --active | head -n1 | cut -d: -f1)
  if [[ -n "$CONN" ]]; then
    need_root nmcli connection modify "$CONN" ipv4.dns "$PRIMARY $BACKUP"
    need_root nmcli connection modify "$CONN" ipv4.ignore-auto-dns yes
    need_root nmcli connection up "$CONN"
    echo "Configured NetworkManager connection '$CONN': $PRIMARY / $BACKUP"
  else
    echo "No active NetworkManager connection found." >&2
    exit 1
  fi
else
  # Last resort: static resolv.conf (may be overwritten by DHCP)
  need_root tee /etc/resolv.conf >/dev/null <<EOF
# Managed by fw-audit harden — filtered DNS
nameserver $PRIMARY
nameserver $BACKUP
EOF
  echo "Wrote /etc/resolv.conf with $PRIMARY and $BACKUP"
fi
""",
        encoding="utf-8",
    )
    paths["setup_dns"] = setup_dns

    drift_sh = scripts_dir / "fw-audit-drift.sh"
    drift_sh.write_text(
        f"""#!/usr/bin/env bash
# Daily drift check installed by fw-audit harden
set -euo pipefail
WORKDIR="{drift_workdir}"
BASELINE="{baseline_s}"
BIN="{fw_audit_bin}"
mkdir -p "$WORKDIR/current" "$WORKDIR/imports/localhost"
ss -tulpn > "$WORKDIR/imports/localhost/ss.txt" 2>/dev/null \\
  || netstat -tulpn > "$WORKDIR/imports/localhost/ss.txt"
"$BIN" report "$WORKDIR/imports" -o "$WORKDIR/current"
if [[ -f "$BASELINE" ]]; then
  set +e
  "$BIN" diff "$BASELINE" "$WORKDIR/current/audit-report.xml" --format text
  rc=$?
  set -e
  if [[ $rc -eq 1 ]]; then
    echo "fw-audit: configuration drift detected" >&2
  fi
  exit 0
fi
echo "No baseline at $BASELINE; current report only."
""",
        encoding="utf-8",
    )
    paths["drift"] = drift_sh

    setup_cron = scripts_dir / "06-setup-cron.sh"
    setup_cron.write_text(
        common_header
        + f"""
DRIFT_SRC="{drift_sh}"
DRIFT_DST="/usr/local/sbin/fw-audit-drift.sh"
CRON_FILE="/etc/cron.d/fw-audit-drift"
need_root install -m 0755 "$DRIFT_SRC" "$DRIFT_DST"
need_root mkdir -p "{drift_workdir}"
need_root cp "{baseline_s}" "{drift_workdir}/baseline-audit-report.xml" 2>/dev/null || true
need_root tee "$CRON_FILE" >/dev/null <<EOF
# fw-audit configuration drift (generated by harden)
{CRON_SCHEDULE} root $DRIFT_DST >> /var/log/fw-audit-drift.log 2>&1
EOF
need_root chmod 644 "$CRON_FILE"
echo "Installed cron job $CRON_FILE ($CRON_SCHEDULE)"
""",
        encoding="utf-8",
    )
    paths["setup_cron"] = setup_cron

    run_all = scripts_dir / "00-run-all.sh"
    run_all.write_text(
        common_header
        + f"""
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
"$SCRIPT_DIR/01-install-deps.sh"
"$SCRIPT_DIR/02-apply-firewall.sh"
"$SCRIPT_DIR/03-setup-fail2ban.sh"
# OpenCanary and DNS are optional — pass OPENCANARY=1 DNS=1 to enable
if [[ "${{OPENCANARY:-0}}" == "1" ]]; then
  "$SCRIPT_DIR/04-setup-opencanary.sh"
fi
if [[ "${{DNS:-0}}" == "1" ]]; then
  "$SCRIPT_DIR/05-setup-dns.sh"
fi
"$SCRIPT_DIR/06-setup-cron.sh"
echo "Harden scripts finished for {distro.pretty_name}."
""",
        encoding="utf-8",
    )
    paths["run_all"] = run_all

    readme = scripts_dir / "README.txt"
    readme.write_text(
        "\n".join(
            [
                "fw-audit Linux harden scripts",
                "=" * 40,
                f"Host: {distro.pretty_name}",
                f"Family: {distro.family.value} (package manager: {distro.package_manager})",
                f"Omarchy: {distro.is_omarchy}",
                "",
                "Stage order:",
                "  1. discover   — ss/netstat open ports",
                "  2. configure  — nftables + Fail2ban + OpenCanary artifacts",
                "  3. firewall   — 02-apply-firewall.sh",
                "  4. fail2ban   — 01-install-deps.sh + 03-setup-fail2ban.sh",
                "  5. opencanary — 04-setup-opencanary.sh (optional Y/n)",
                "  6. dns        — 05-setup-dns.sh → "
                f"{PRIMARY_DNS} + {BACKUP_DNS} backup (optional Y/n)",
                "  7. cron       — 06-setup-cron.sh (fw-audit drift)",
                "",
                f"Artifacts under: {host_out_s}",
                "Prefer: fw-audit harden --apply  (prompts for optional stages)",
                "Or run scripts individually after review.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    paths["readme"] = readme

    for path in paths.values():
        if path.suffix == ".sh":
            path.chmod(path.stat().st_mode | 0o111)

    return paths
